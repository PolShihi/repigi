class Order(models.Model):
    """
Represents an order in the pharmacy system.

Attributes:
    medication (ForeignKey): The medication associated with the order.
    client (ForeignKey): The client who placed the order.
    department (ForeignKey): The pharmacy department where the order was placed.
    quantity (PositiveIntegerField): The quantity of medication ordered.
    date_of_order (DateTimeField): The date and time when the order was placed.
    promo (ForeignKey): The promotional offer applied to the order, if any.

Methods:
    __str__(): Returns a string representation of the order showing the client and medication.
    get_total_cost(): Calculates the total cost of the order taking into account the medication cost, quantity, and any active promotional discount.
"""
    medication = models.ForeignKey(Medication, on_delete=models.CASCADE)
    client = models.ForeignKey(Client, on_delete=models.CASCADE)
    department = models.ForeignKey(PharmacyDepartment, on_delete=models.CASCADE)
    quantity = models.PositiveIntegerField()
    date_of_order = models.DateTimeField(auto_now_add=True)
    promo = models.ForeignKey(Promo, on_delete=models.SET_NULL, null=True, blank=True)
    
    def __str__(self):
        return str(self.client) + ', ' + str(self.medication)
    
    def get_total_cost(self):
        return round(self.medication.cost * self.quantity * (self.promo.discount if (self.promo is not None and self.promo.is_active) else 1), 2)
    
    
