class MedicationCategory(models.Model):
    """
Represents a category for medications.

Attributes:
    name (str): The name of the medication category.
    description (str): The description of the medication category.
"""
    name = models.CharField(max_length=100)
    description = models.TextField()

    def __str__(self):
        return self.name

class Supplier(models.Model):
    """
Represents a supplier in the pharmacy system.

Attributes:
    company_name (str): The name of the supplier company.
    phone (str): The phone number of the supplier.
    address (str): The address of the supplier.

Methods:
    __str__(): Returns the company name of the supplier.
    get_list_of_orders(): Retrieves a list of orders associated with the supplier's medications.
"""
    company_name = models.CharField(max_length=100)
    phone = models.CharField(max_length=20)
    address = models.CharField(max_length=200)

    def __str__(self):
        return self.company_name
    
    def get_list_of_orders(self):
        return [order for medication in self.medication_set.all() for order in medication.order_set.all()]

class PharmacyDepartment(models.Model):
    """
Represents a department within the pharmacy system.

Attributes:
    address (str): The address of the pharmacy department.

Methods:
    __str__(): Returns the address of the pharmacy department.
    get_total_revenue(): Calculates the total revenue generated by summing the total cost of all orders associated with the department.
"""
    address = models.CharField(max_length=200)

    def __str__(self):
        return self.address
    
    def get_total_revenue(self):
        return sum((order.get_total_cost() for order in self.order_set.all()))

class Medication(models.Model):
    """
Represents a medication in the pharmacy system.

Attributes:
    code (str): The unique code of the medication.
    name (str): The name of the medication.
    instruction (str): The instructions for using the medication.
    description (str): The description of the medication.
    cost (Decimal): The cost of the medication.
    photo (ImageField): The photo of the medication.
    categories (ManyToManyField): The categories that the medication belongs to.
    supplier (ForeignKey): The supplier of the medication.
    date_created (DateTimeField): The date and time when the medication was created.

Methods:
    __str__(): Returns the name of the medication.
    get_total_revenue(): Calculates the total revenue generated by the medication through orders.
    get_total_number_of_ordered(): Calculates the total number of units ordered for the medication.
"""
    code = models.CharField(max_length=20, unique=True)
    name = models.CharField(max_length=100)
    instruction = models.TextField()
    description = models.TextField()
    cost = models.DecimalField(max_digits=8, decimal_places=2)
    photo = models.ImageField(upload_to='medication_photos')
    categories = models.ManyToManyField(MedicationCategory)
    supplier = models.ForeignKey(Supplier, on_delete=models.SET_NULL, null=True, blank=True)
    date_created = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return self.name
    
    def get_total_revenue(self):
        return sum((order.get_total_cost() for order in self.order_set.all()))
    
    def get_total_number_of_ordered(self):
        return sum((order.quantity for order in self.order_set.all()))

class Employee(models.Model):
    """
Represents an employee in the pharmacy system.

Attributes:
    user (User): The user associated with the employee.
    date_of_birth (DateFiels): The date of birth of user.
    phone (str): The phone number of the employee.
    position (str): The position/title of the employee.
    salary (Decimal): The salary of the employee.
    photo (ImageField): The photo of the employee.
    timezone_info (str): The timezone information for the employee.
    suppliers (ManyToManyField): The suppliers associated with the employee.

Methods:
    __str__(): Returns the full name of the user associated with the employee.
"""
    user = models.OneToOneField(User, on_delete=models.CASCADE)
    date_of_birth = models.DateField()
    phone = models.CharField(max_length=20, default='')
    position = models.CharField(max_length=100)
    salary = models.DecimalField(max_digits=10, decimal_places=2)
    photo = models.ImageField(upload_to='employee_photos')
    timezone_info = models.CharField(max_length=32, choices=tuple((el, el) for el in COMMON_TIMEZONES))
    suppliers = models.ManyToManyField(Supplier)

    def __str__(self):
        return self.user.get_full_name()
    
    def get_age(self):
        today = timezone.now().date()
        age = today.year - self.date_of_birth.year - ((today.month, today.day) < (self.date_of_birth.month, self.date_of_birth.day))
        return age
    
